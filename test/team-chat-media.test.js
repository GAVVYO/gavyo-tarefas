import assert from 'node:assert/strict';
import {test} from 'node:test';
import {once} from 'node:events';
import {randomUUID} from 'node:crypto';
import {mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {openDatabase} from '../src/db.js';
import {createStore} from '../src/store.js';
import {createApp} from '../src/app.js';

test('chat: imagens autenticadas, autoria de anexos, cartões e reenvio idempotente',async t=>{
 const db=await openDatabase({path:':memory:'}),store=createStore(db);
 const uploads=await mkdtemp(join(tmpdir(),'chat-media-'));
 const server=createApp(store,{uploads}).listen(0,'127.0.0.1'); await once(server,'listening');
 t.after(async()=>{await new Promise(r=>server.close(r));await db.close();await rm(uploads,{recursive:true,force:true});});
 const base=`http://127.0.0.1:${server.address().port}`;
 const a=await store.createMember({name:'Bola'}),b=await store.createMember({name:'Felipe'});
 const ca='gavyo_session='+(await store.login(a.id,'1234')).token,cb='gavyo_session='+(await store.login(b.id,'1234')).token;
 const project=await store.createProject({name:'Teste'}),card=await store.createCard({title:'Cartão mencionado',projectId:project.id},{...a,source:'Web'});
 const png=Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aN1sAAAAASUVORK5CYII=','base64');
 const upload=(cookie,body=png,type='image/png')=>fetch(base+'/api/team/images',{method:'POST',headers:{...(cookie?{cookie}:{}),'content-type':type},body});
 assert.equal((await upload()).status,401);
 assert.equal((await upload(ca,Buffer.from('not png'))).status,400);
 assert.equal((await upload(ca,Buffer.from('<svg/>'),'image/svg+xml')).status,403);
 const response=await upload(ca);assert.equal(response.status,201);const image=await response.json();
 assert.equal((await fetch(base+image.url)).status,401);
 const read=await fetch(base+image.url,{headers:{cookie:cb}});assert.equal(read.status,200);assert.match(read.headers.get('content-type'),/image\/png/);assert.equal((await read.arrayBuffer()).byteLength,png.length);
 const post=(cookie,payload)=>fetch(base+'/api/team/messages',{method:'POST',headers:{cookie,'content-type':'application/json'},body:JSON.stringify(payload)});
 const payload={clientId:randomUUID(),images:[image.id],cards:[card.id]};
 assert.equal((await post(cb,payload)).status,403);
 const sent=await post(ca,payload);assert.equal(sent.status,201);const message=await sent.json();
 assert.equal(message.text,'');assert.equal(message.images[0].url,image.url);assert.equal(message.cards[0].key,card.key);assert.equal(message.author.id,a.id);
 assert.equal((await (await post(ca,payload)).json()).id,message.id);
 assert.equal((await post(ca,{...payload,cards:[]})).status,409);
 assert.equal((await post(ca,{clientId:randomUUID(),cards:[randomUUID()]})).status,404);
 assert.equal((await post(ca,{clientId:randomUUID(),images:Array(5).fill(image.id)})).status,400);
 const history=await (await fetch(base+'/api/team/messages',{headers:{cookie:cb}})).json();assert.equal(history.messages.length,1);assert.equal(history.messages[0].images[0].id,image.id);
});
